// gnox — build the router commands from the marketplace
//
// Writes plugins/gnox/commands/ from .claude-plugin/marketplace.json and each listed
// plugin's skills/<skill>/SKILL.md, so every skill in the marketplace is reachable as
//
//   /gnox:<plugin>                  the plugin's main skill (the skill named like the
//                                   plugin), or, when it has none, a list of its commands
//   /gnox:<plugin>:<skill>          any other skill of the plugin
//   /gnox:<plugin>:<group>:<cmd>    the plugin's own command /<plugin>:<group>:<cmd>
//                                   (its commands/<group>/<cmd>.md), at any depth
//
// Claude Code turns commands/<plugin>.md into /gnox:<plugin> and each subfolder level
// into one more segment. Each command hands its arguments to the plugin's own skill or
// command, so the plugin must be installed for it to work. Where a skill and a command
// of the same plugin would land on the same name, the skill wins.
// Every generated file carries GENERATED_MARK; a file under commands/ without it is
// left alone, and a generated file nothing produces any more is removed.
//
//   node plugins/gnox/scripts/build-commands.js           write the commands
//   node plugins/gnox/scripts/build-commands.js --check   exit 1 if any file would change
//
// Cross-platform per marketplace CLAUDE.md: pure Node, no child_process, no hardcoded
// Unix paths, every fs call wrapped.

'use strict';

const fs = require('fs');
const path = require('path');

const PLUGIN_DIR = path.resolve(__dirname, '..');
const ROOT = path.resolve(PLUGIN_DIR, '..', '..');
const COMMANDS = path.join(PLUGIN_DIR, 'commands');
const SELF = 'gnox';
const GENERATED_MARK = '<!-- generated by plugins/gnox/scripts/build-commands.js; edit the plugin\'s skill, not this file -->';

function readText(p) {
  try { return fs.readFileSync(p, 'utf8'); } catch { return null; }
}

function listDirs(p) {
  try {
    return fs.readdirSync(p, { withFileTypes: true }).filter((d) => d.isDirectory()).map((d) => d.name).sort();
  } catch { return []; }
}

// name and description from a SKILL.md front matter block: plain, quoted, or a `>` / `|` block scalar.
function frontMatter(text) {
  const m = /^---\r?\n([\s\S]*?)\r?\n---/.exec(text || '');
  if (!m) return {};
  const lines = m[1].split(/\r?\n/);
  const out = {};
  for (let i = 0; i < lines.length; i++) {
    const kv = /^(name|description):\s*(.*)$/.exec(lines[i]);
    if (!kv) continue;
    let value = kv[2].trim();
    if (value === '>' || value === '|' || value === '>-' || value === '|-') {
      const parts = [];
      while (i + 1 < lines.length && /^\s+\S/.test(lines[i + 1])) parts.push(lines[++i].trim());
      value = parts.join(' ');
    } else if (/^".*"$/.test(value)) {
      try { value = JSON.parse(value); } catch { value = value.slice(1, -1); }
    } else if (/^'.*'$/.test(value)) {
      value = value.slice(1, -1).replace(/''/g, "'");
    }
    out[kv[1]] = value;
  }
  return out;
}

// One line for the / menu: the first sentence, at most 200 characters.
function summary(text) {
  const t = String(text || '').replace(/\s+/g, ' ').trim();
  const first = (/^(.+?[.!?])(\s|$)/.exec(t) || [null, t])[1];
  return first.length <= 200 ? first : first.slice(0, 197).trimEnd() + '...';
}

function skillsOf(pluginDir) {
  return listDirs(path.join(pluginDir, 'skills')).map((dir) => {
    const fm = frontMatter(readText(path.join(pluginDir, 'skills', dir, 'SKILL.md')));
    return { name: fm.name || dir, description: fm.description || '' };
  }).filter((s) => s.name);
}

// A plugin's own commands: commands/**/*.md, each as { name: 'group:cmd', description }.
function commandsOf(pluginDir) {
  const out = [];
  const walk = (dir, segs) => {
    let entries = [];
    try { entries = fs.readdirSync(dir, { withFileTypes: true }); } catch { return; }
    for (const e of entries.sort((a, b) => (a.name < b.name ? -1 : 1))) {
      if (e.isDirectory()) walk(path.join(dir, e.name), [...segs, e.name]);
      else if (e.name.endsWith('.md')) {
        const fm = frontMatter(readText(path.join(dir, e.name)));
        out.push({ name: [...segs, e.name.slice(0, -3)].join(':'), description: fm.description || '' });
      }
    }
  };
  walk(path.join(pluginDir, 'commands'), []);
  return out;
}

// kind is 'skill' or 'command'; item.name is the part after `<plugin>:`.
function runFile(plugin, item, kind, marketplace) {
  const target = `${plugin}:${item.name}`;
  return [
    '---',
    `description: ${JSON.stringify(summary(item.description) || `Run the ${target} ${kind}.`)}`,
    'argument-hint: "[arguments]"',
    '---',
    GENERATED_MARK,
    '',
    `Run the \`${target}\` ${kind} (plugin \`${plugin}\`) with the Skill tool, passing these arguments: $ARGUMENTS`,
    '',
    `If the \`${plugin}\` plugin is not installed, say so and give the install line: \`/plugin install ${plugin}@${marketplace}\`.`,
    '',
  ].join('\n');
}

function indexFile(plugin, description, others, marketplace) {
  const lines = [
    '---',
    `description: ${JSON.stringify(`${summary(description) || plugin} (lists its commands)`)}`,
    '---',
    GENERATED_MARK,
    '',
  ];
  if (others.length === 0) {
    lines.push(`The \`${plugin}\` plugin has no commands; it works through its hooks. Tell the user so.`);
  } else {
    lines.push(`List these commands of the \`${plugin}\` plugin for the user, each with its line:`, '');
    for (const s of others) lines.push(`- \`/gnox:${plugin}:${s.name}\`: ${summary(s.description)}`);
  }
  lines.push('', `Install line, if it is not installed: \`/plugin install ${plugin}@${marketplace}\`.`, '');
  return lines.join('\n');
}

// Every file the marketplace calls for, as { relative path under commands/: text }.
function wanted() {
  const mp = JSON.parse(readText(path.join(ROOT, '.claude-plugin', 'marketplace.json')) || '{}');
  const marketplace = mp.name || 'gnomatix-oss-skills';
  const files = new Map();
  for (const entry of mp.plugins || []) {
    const plugin = entry.name;
    if (!plugin || plugin === SELF || typeof entry.source !== 'string') continue;
    const dir = path.resolve(ROOT, entry.source);
    const skills = skillsOf(dir);
    const main = skills.find((s) => s.name === plugin);
    const others = skills.filter((s) => s.name !== plugin);
    const commands = commandsOf(dir).filter((c) => c.name !== plugin && !others.some((s) => s.name === c.name));
    const listed = [...others, ...commands];
    files.set(`${plugin}.md`, main ? runFile(plugin, main, 'skill', marketplace) : indexFile(plugin, entry.description, listed, marketplace));
    for (const s of others) files.set(path.join(plugin, `${s.name}.md`), runFile(plugin, s, 'skill', marketplace));
    for (const c of commands) files.set(path.join(plugin, ...c.name.split(':')) + '.md', runFile(plugin, c, 'command', marketplace));
  }
  return files;
}

function existingGenerated(dir, base = '') {
  const out = [];
  let entries = [];
  try { entries = fs.readdirSync(dir, { withFileTypes: true }); } catch { return out; }
  for (const e of entries) {
    const rel = path.join(base, e.name);
    if (e.isDirectory()) out.push(...existingGenerated(path.join(dir, e.name), rel));
    else if (e.name.endsWith('.md') && (readText(path.join(dir, e.name)) || '').includes(GENERATED_MARK)) out.push(rel);
  }
  return out;
}

function writeAtomic(p, text) {
  fs.mkdirSync(path.dirname(p), { recursive: true });
  const tmp = `${p}.tmp-${process.pid}`;
  fs.writeFileSync(tmp, text, 'utf8');
  fs.renameSync(tmp, p);
}

function main() {
  const check = process.argv.includes('--check');
  const files = wanted();
  const changes = [];
  for (const [rel, text] of files) if (readText(path.join(COMMANDS, rel)) !== text) changes.push(['write', rel, text]);
  for (const rel of existingGenerated(COMMANDS)) if (!files.has(rel)) changes.push(['remove', rel]);
  if (check) {
    for (const [op, rel] of changes) process.stdout.write(`would ${op}: commands/${rel.split(path.sep).join('/')}\n`);
    process.stdout.write(`${changes.length} change(s); ${files.size} command file(s) expected\n`);
    process.exit(changes.length ? 1 : 0);
  }
  for (const [op, rel, text] of changes) {
    const p = path.join(COMMANDS, rel);
    try {
      if (op === 'write') writeAtomic(p, text);
      else fs.rmSync(p, { force: true });
    } catch (err) {
      process.stderr.write(`[gnox build-commands] ${op} ${rel} failed: ${err && err.message}\n`);
      process.exit(1);
    }
  }
  process.stdout.write(`${changes.length} change(s); ${files.size} command file(s)\n`);
}

main();
